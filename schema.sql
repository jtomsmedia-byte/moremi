PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS leads(email TEXT PRIMARY KEY,name TEXT);
CREATE TABLE IF NOT EXISTS applications(email TEXT PRIMARY KEY,name TEXT,answers TEXT,status TEXT DEFAULT 'submitted',invite TEXT,expires INTEGER);
CREATE TABLE IF NOT EXISTS users(email TEXT PRIMARY KEY,name TEXT,role TEXT,joined TEXT);
CREATE TABLE IF NOT EXISTS challenges(id TEXT PRIMARY KEY,email TEXT,proof TEXT,invite TEXT,expires INTEGER,tries INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS sessions(id TEXT PRIMARY KEY,email TEXT,expires INTEGER);
CREATE TABLE IF NOT EXISTS limits(key TEXT PRIMARY KEY,count INTEGER,expires INTEGER);
CREATE TABLE IF NOT EXISTS content(id INTEGER PRIMARY KEY,kind TEXT,title TEXT,body TEXT,file TEXT,live INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS messages(id INTEGER PRIMARY KEY,email TEXT,body TEXT);
CREATE TABLE IF NOT EXISTS projects(id INTEGER PRIMARY KEY,email TEXT,title TEXT,file TEXT,status TEXT DEFAULT 'submitted',feedback TEXT DEFAULT '');
CREATE UNIQUE INDEX IF NOT EXISTS one_project ON projects(email);
CREATE TABLE IF NOT EXISTS milestones(email TEXT,stage TEXT,PRIMARY KEY(email,stage));